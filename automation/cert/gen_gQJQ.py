"""Generator of the certificate files for (6.25) ([DIR] §6.5, Case QJQ):
g_{QJQ,beta}(x,y) > 1e-5 on [1/4, 1/2] x [1/2, 3/4] for beta in {beta_1, 1/2}, with the
admissible partitions `g_QJQ` (beta_1, 55 rectangles) and `g_QJQh` (beta = 1/2, 181 rectangles)
of the paper's `partitions.py`, refined dyadically where needed.

This file was automatically generated by Claude.

The paper's partitions were produced by the companion code with the term J(y_l)J'(y_l) (an upper
bound of J(y)J'(y) on the rectangle) instead of the paper's J(y_u)J'(y_u); with the (correct)
lower bound `Auto.DIR.g_QJQ_lo` most of their rectangles have to be subdivided.

Usage (from the repository root): python3 automation/cert/gen_gQJQ.py
Writes Isoperim/DIR/6_Proof_Two_Point_Inequality/6_5_Case_QJQ_aux_cert_*.lean.
"""
import mpmath as mp
from fractions import Fraction as F
from gen_common import boxes, build_tree, lean_tree, q, header, FOOTER, write, DIR
from gen_qj_common import J, DJ, Q, Q1, refine, chain, emit_boxes, cases_proof, wrap_doc, J_entry, DJ_entry

NTAB = 300
NBOX = 700
THR = mp.mpf("1e-5") + mp.mpf("1e-8")
ROOT = (F(1, 4), F(1, 2), F(1, 2), F(3, 4))
CASES = [  # (tag, partition, beta, Lean beta, PowVal, PowVal lemma, description)
    ("b1", "g_QJQ", mp.mpf(1) / 2 + mp.mpf(31) / 1024, "(2⁻¹ + 31 / 1024 : ℝ)", "tβ₁", "tβ₁_v",
     "$\\beta=\\beta_1$"),
    ("h", "g_QJQh", mp.mpf(1) / 2, "(2⁻¹ : ℝ)", "tHalf", "tHalf_v", "$\\beta=\\frac12$"),
]


def Qbar(t, a, b):
    if Q1(t, b) < 0:
        return Q(t, a) + max(Q1(t, a), 0) * (b - a)
    return Q(t, b)


def lo(t):
    """`Auto.DIR.g_QJQ_lo` (floating point)."""
    def f(xl, xu, yl, yu):
        ml, mh = (xl + yl) / 2, (xl + yu) / 2
        B = Q1(t, ml)
        A1 = 2 * Qbar(t, ml, mh) - Q(t, xl)
        A2 = 2 * min(Q(t, (xu + yl) / 2), Q(t, (xu + yu) / 2)) - Q(t, xu)
        return (yl - xu) + J(yu) * DJ(yu) - max(A1 * B, A2 * B)
    return f


def main():
    parts = {}
    for tag, pname, beta, *_ in CASES:
        f = lo(mp.mpf(2) ** beta)
        bs = [r for b in boxes(pname) for r in refine(f, b, THR)]
        tree, order = build_tree(bs, *ROOT)
        parts[tag] = (tree, order)
        print(tag, pname, len(boxes(pname)), "->", len(order))
    pts = sorted({b[3] for tag in parts for b in parts[tag][1]})
    nJ = {p: f"tQJQJ_{i}" for i, p in enumerate(pts)}
    nD = {p: f"tQJQD_{i}" for i, p in enumerate(pts)}
    tabmods = []
    for k in range(0, len(pts), NTAB):
        mod = f"6_5_Case_QJQ_aux_cert_tab_{k // NTAB}"
        tabmods.append(mod)
        doc = ("Certified values of $J$ and $J'$ (table entries) for the box certificates of (6.25) "
               f"([DIR], §6.5), part {k // NTAB}. Generated by `automation/cert/gen_gQJQ.py`.")
        txt = header(["6_5_Case_QJQ_aux_cert"],
                     f"[DIR] (6.25): table of $J$, $J'$, part {k // NTAB}", wrap_doc(doc))
        for p in pts[k:k + NTAB]:
            txt += J_entry(nJ[p], p) + DJ_entry(nD[p], p)
        txt += FOOTER
        write(f"{DIR}/{mod}.lean", txt)
    allmods = []
    for tag, pname, beta, lb, tv, tvl, desc in CASES:
        tree, order = parts[tag]
        chunks = [order[i:i + NBOX] for i in range(0, len(order), NBOX)]
        boxmods = []
        for k, chunk in enumerate(chunks):
            mod = f"6_5_Case_QJQ_aux_cert_{tag}_{k}"
            boxmods.append(mod)
            doc = (f"Box certificates of (6.25) ([DIR], §6.5) for {desc}, part {k}: "
                   "$\\underline{g_{QJQ,\\beta}}>10^{-5}$ on each rectangle of the partition (one "
                   "kernel evaluation each). Generated by `automation/cert/gen_gQJQ.py`.")

            def proof(p, tv=tv, tvl=tvl):
                return f"gQJQ_box _ {tv} {tvl} _ {nJ[p[3]]} {nD[p[3]]} (by decide +kernel)"
            emit_boxes(f"gQJQ_{tag}_{k}", mod, tabmods, f"[DIR] (6.25): box certificates, {tag}, part {k}",
                       doc, chunk, proof, f"gQJQ_fl {lb}", header, FOOTER, write, DIR)
        allmods += boxmods
        # assembly
        mod = f"6_5_Case_QJQ_aux_cert_{tag}"
        allmods.append(mod)
        doc = (f"Assembly of the computer-assisted proof of (6.25) ([DIR], §6.5) for {desc}: the "
               f"dyadic tree of the partition (`{pname}` of the paper's `partitions.py`, refined), "
               "the box certificates and soundness of partitioning (`Auto.DIR.gQJQ_of_tree`, via "
               "[DIR] Fact 4.1). Generated by `automation/cert/gen_gQJQ.py`.")
        txt = header(boxmods, f"[DIR] (6.25): assembly, {tag}", wrap_doc(doc))
        txt += (f"/-- The dyadic tree of the partition of $[\\frac14,\\frac12]\\times"
                f"[\\frac12,\\frac34]$\nfor (6.25), {desc}. -/\ndef gQJQTree_{tag} : DTree :=\n  "
                + lean_tree(tree) + "\n\n")
        names = [f"gQJQ_{tag}_{k}s" for k in range(len(chunks))]
        R = " ".join(q(r) for r in ROOT)
        txt += ("/-- The rectangles of the tree are the rectangles of the box certificates. -/\n"
                f"theorem gQJQTree_{tag}_boxes :\n    gQJQTree_{tag}.boxes {R} =\n      {chain(names)} := by\n"
                "  decide +kernel\n\n")
        txt += (f"/-- **(6.25)** for {desc}: $g_{{QJQ,\\beta}}>10^{{-5}}$ on\n"
                "$[\\frac14,\\frac12]\\times[\\frac12,\\frac34]$. -/\n"
                f"theorem gQJQ_pos_{tag} : ∀ x ∈ Icc (4⁻¹ : ℝ) 2⁻¹, ∀ y ∈ Icc (2⁻¹ : ℝ) (3 / 4),\n"
                f"    1 / 10 ^ 5 < (y - x) + J y * DJr y -\n"
                f"      (2 * Q {lb} ((x + y) / 2) - Q {lb} x) *\n"
                f"        Q1f {lb} ((x + y) / 2) := by\n"
                f"  refine gQJQ_of_tree _ (by norm_num) gQJQTree_{tag} ?_\n"
                f"  rw [gQJQTree_{tag}_boxes]\n  intro p hp\n" + cases_proof(names) + "\n")
        txt += FOOTER
        write(f"{DIR}/{mod}.lean", txt)
    print("modules:", tabmods + allmods)


if __name__ == "__main__":
    main()
