def emit_assembly(mod, boxmods, title, doc, treename, tree, root, chunk_names, pos_name,
                  pos_doc, pos_stmt, of_tree, header, FOOTER, write, DIR):
    """Write the assembly file: the dyadic tree, the equality of its rectangles with the
    concatenation of the lists of the box files (by `decide +kernel`) and the final positivity
    `pos_name : pos_stmt`, proved by `refine of_tree ?_` (soundness of partitioning)."""
    txt = header(boxmods, title, wrap_doc(doc))
    txt += (f"/-- The dyadic tree of the partition. -/\ndef {treename} : DTree :=\n  "
            + lean_tree(tree) + "\n\n")
    R = " ".join(q(r) for r in root)
    txt += ("/-- The rectangles of the tree are the rectangles of the box certificates. -/\n"
            f"theorem {treename}_boxes :\n    {treename}.boxes {R} =\n      "
            + "\n        ".join(textwrap.wrap(chain(chunk_names), 90)) + " := by\n"
            "  decide +kernel\n\n")
    txt += (f"/-- {pos_doc} -/\ntheorem {pos_name} :\n{pos_stmt} := by\n"
            f"  refine {of_tree} {treename} ?_\n"
            f"  rw [{treename}_boxes]\n  intro p hp\n" + cases_proof(chunk_names) + "\n")
    txt += FOOTER
    write(f"{DIR}/{mod}.lean", txt)
