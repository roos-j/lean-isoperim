def chain(names):
    """`a ++ (b ++ (c ...))`."""
    cat = names[-1]
    for nm in reversed(names[:-1]):
        cat = f"{nm} ++ ({cat})"
    return cat


def qs(x):
    """Short Lean rational literal (inside a `Box`, whose type fixes ℚ)."""
    x = F(x)
    assert x >= 0
    return f"{x.numerator}" if x.denominator == 1 else f"{x.numerator} / {x.denominator}"


def tup(p):
    return "(" + ", ".join(qs(c) for c in p) + ")"


def wrap_doc(doc, width=100):
    """Wrap a module docstring paragraph."""
    import textwrap
    return "\n".join(textwrap.wrap(doc, width, break_on_hyphens=False, break_long_words=False))


def emit_boxes(prefix, mod, imports, title, doc, chunk, box_proof, fl_name, header,
               FOOTER, write, DIR):
    """Write one box-certificate file with one lemma per rectangle (`0 < fl_name` on it, proved
    by `box_proof(p)`), the list of its rectangles and the positivity on the list."""
    txt = header(imports, title, wrap_doc(doc))
    lst = []
    names = []
    for i, p in enumerate(chunk):
        xl, xu, yl, yu = p
        b = f"{prefix}_{i}"
        names.append(b)
        lst.append(f"({q(xl)}, {q(xu)}, {q(yl)}, {q(yu)})")
        txt += (f"/-- Box certificate on $[{xl},{xu}]\\times[{yl},{yu}]$. -/\n"
                f"theorem {b} :\n    0 < {fl_name} (Box.toR {tup(p)}).1\n"
                f"      (Box.toR {tup(p)}).2 :=\n  {box_proof(p)}\n\n")
    txt += (f"set_option maxRecDepth 100000 in\n/-- The rectangles of this part of the partition. -/\n"
            f"def {prefix}s : List Box :=\n  [" + ",\n   ".join(lst) + "]\n\n")
    body = ", ".join(names)
    import textwrap
    body = "\n     ".join(textwrap.wrap(body, 92))
    txt += (f"set_option maxRecDepth 100000 in\n/-- The lower bound is positive on the rectangles of "
            f"this part. -/\ntheorem {prefix}s_pos :\n    ∀ p ∈ {prefix}s, 0 < {fl_name} (Box.toR p).1"
            f" (Box.toR p).2 :=\n  List.forall_iff_forall_mem.mp\n    ⟨" + body + "⟩\n\n")
    txt += FOOTER
    write(f"{DIR}/{mod}.lean", txt)


def cases_proof(names):
    """Tactic proof of `∀ p ∈ L₀ ++ (L₁ ++ ...), P p` from `hp` and the lemmas `<name>_pos`."""
    if len(names) == 1:
        return f"  exact {names[0]}_pos p hp\n"
    return ("  simp only [List.mem_append] at hp\n  rcases hp with " + " | ".join("h" for _ in names)
            + "\n" + "".join(f"  · exact {n}_pos p h\n" for n in names))


