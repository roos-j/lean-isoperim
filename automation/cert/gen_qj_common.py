def refine(f, b, thr, depth=0, maxdepth=16):
    """Dyadic refinement of the rectangle b = (xl, xu, yl, yu) until f > thr on each piece."""
    if f(*b) > thr:
        return [b]
    if depth >= maxdepth:
        raise ValueError(f"refinement failed at {b}")
    xl, xu, yl, yu = b
    mx, my = (xl + xu) / 2, (yl + yu) / 2
    out = []
    for c in [(xl, mx, yl, my), (xl, mx, my, yu), (mx, xu, yl, my), (mx, xu, my, yu)]:
        out += refine(f, c, thr, depth + 1, maxdepth)
    return out


