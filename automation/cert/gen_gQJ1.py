"""Generator of the certificate files for (6.26) ([DIR] §6.6.1, Case QJ near diagonal):
-beta d_x g_{QJ,beta,c}(x,y) > 1e-5 on [1/4, 1/2] x [1/2, 5/8] for (beta, c) in
{(beta_0, 1), (1/2, c_0)}, with the admissible partitions `g_QJ_1` (439 rectangles) and `g_QJ_1h`
(430 rectangles) of the paper's `partitions.py`, refined dyadically where needed.

This file was automatically generated by Claude.

The companion code decides the case of the tight lower bound by `xM < x0` (always true here)
instead of the paper's (m_u < x0), m_u = (x_u + y_u)/2; for the rectangles with m_u > x0 the
paper's lower bound needs a few subdivisions.

Usage (from the repository root): python3 automation/cert/gen_gQJ1.py
Writes Isoperim/DIR/6_Proof_Two_Point_Inequality/6_6_Case_QJ_aux_cert_g1_*.lean.
"""
import mpmath as mp
from fractions import Fraction as F
from gen_common import boxes, build_tree, header, FOOTER, write, DIR
from gen_qj_common import (J, DJ, Q, Q1, X0, X0L, X0U, refine, emit_boxes, emit_assembly,
                           wrap_doc, Jw_entry, DJw_entry, mpf)

NTAB = 150     # points per table file (two entries each)
NBOX = 700
THR = mp.mpf("1e-5") + mp.mpf("1e-8")
ROOT = (F(1, 4), F(1, 2), F(1, 2), F(5, 8))
CASES = [  # (tag, partition, beta, c, Lean beta, Lean c, check function, description)
    ("b0", "g_QJ_1", mp.mpf("0.50057"), mp.mpf(1), "β₀", "1", "gQJ1_box_b0",
     "$(\\beta,c)=(\\beta_0,1)$"),
    ("h", "g_QJ_1h", mp.mpf(1) / 2, mp.mpf("0.997"), "2⁻¹", "c₀", "gQJ1_box_h",
     "$(\\beta,c)=(\\frac12,c_0)$"),
]


def case(xl, xu, yl, yu):
    """The case of the lower bound, decided with the rational enclosure [X0L, X0U] of x0:
    0: m_u < x0; 1: x0 < m_l; 2: m_l <= x0 <= m_u."""
    ml, mu = (xl + yl) / 2, (xu + yu) / 2
    if mu < X0L:
        return 0
    if X0U < ml:
        return 1
    if X0U <= mu and ml <= X0L:
        return 2
    return None


def lo(beta, c):
    """`Auto.DIR.g_QJ_1_lo` (floating point); -inf if the case is undecided."""
    t = mp.mpf(2) ** beta
    r = 1 / beta - 1
    C = c ** (1 / beta)

    def f(xl, xu, yl, yu):
        k = case(xl, xu, yl, yu)
        if k is None:
            return -mp.inf
        ml, mu = (xl + yl) / 2, (xu + yu) / 2
        Jbar = [J(mu), J(ml), J(X0)][k]
        Db = 2 * Jbar - Q(t, xl)
        rv = mpf(yl - xu) ** r
        if k == 0:
            Dl = max(2 * min(J(ml), J(mu)) - Q(t, xu), 0)
            rv += C * Dl ** r * DJ(mu)
        else:
            rv -= C * Db ** r * max(abs(DJ(ml)), abs(DJ(mu)))
        rv -= C * Db ** r * Q1(t, xl)
        return rv
    return f


def main():
    parts = {}
    for tag, pname, beta, c, *_ in CASES:
        f = lo(beta, c)
        bs = [r for b in boxes(pname) for r in refine(f, b, THR)]
        tree, order = build_tree(bs, *ROOT)
        parts[tag] = (tree, order)
        print(tag, pname, len(boxes(pname)), "->", len(order))
    pts = sorted({m for tag in parts for (xl, xu, yl, yu) in parts[tag][1]
                  for m in ((xl + yl) / 2, (xu + yu) / 2)})
    nW = {p: f"tQJ1W_{i}" for i, p in enumerate(pts)}
    nD = {p: f"tQJ1D_{i}" for i, p in enumerate(pts)}
    tabmods = []
    for k in range(0, len(pts), NTAB):
        mod = f"6_6_Case_QJ_aux_cert_g1_tab_{k // NTAB}"
        tabmods.append(mod)
        doc = ("Certified values of $J_{w_0}$ and $J_{w_0}'$ (table entries) for the box "
               f"certificates of (6.26) ([DIR], §6.6.1), part {k // NTAB}. Generated by "
               "`automation/cert/gen_gQJ1.py`.")
        txt = header(["6_6_Case_QJ_aux_cert"],
                     f"[DIR] (6.26): table of $J_{{w_0}}$, $J_{{w_0}}'$, part {k // NTAB}",
                     wrap_doc(doc))
        for p in pts[k:k + NTAB]:
            txt += Jw_entry(nW[p], p) + DJw_entry(nD[p], p)
        txt += FOOTER
        write(f"{DIR}/{mod}.lean", txt)
    allmods = list(tabmods)
    for tag, pname, beta, c, lb, lc, boxfn, desc in CASES:
        tree, order = parts[tag]
        chunks = [order[i:i + NBOX] for i in range(0, len(order), NBOX)]
        boxmods = []
        fl = f"gQJ1_fl {lb} {lc}"
        for k, chunk in enumerate(chunks):
            mod = f"6_6_Case_QJ_aux_cert_g1_{tag}_{k}"
            boxmods.append(mod)
            doc = (f"Box certificates of (6.26) ([DIR], §6.6.1) for {desc}, part {k}: "
                   "$\\underline{g_{QJ,1,\\beta,c}}>10^{-5}$ on each rectangle of the partition "
                   "(one kernel evaluation each). Generated by `automation/cert/gen_gQJ1.py`.")

            def proof(p, boxfn=boxfn):
                xl, xu, yl, yu = p
                ml, mu = (xl + yl) / 2, (xu + yu) / 2
                return (f"{boxfn} {case(*p)} _ {nW[ml]} {nW[mu]} {nD[ml]} {nD[mu]}\n"
                        f"    (by decide +kernel)")
            emit_boxes(f"gQJ1_{tag}_{k}", mod, tabmods,
                       f"[DIR] (6.26): box certificates, {tag}, part {k}", doc, chunk, proof, fl,
                       header, FOOTER, write, DIR)
        allmods += boxmods
        mod = f"6_6_Case_QJ_aux_cert_g1_{tag}"
        allmods.append(mod)
        doc = (f"Assembly of the computer-assisted proof of (6.26) ([DIR], §6.6.1) for {desc}: "
               f"the dyadic tree of the partition (`{pname}` of the paper's `partitions.py`, "
               "refined), the box certificates and soundness of partitioning "
               "(`Auto.DIR.gQJ1_of_tree`, via [DIR] Fact 4.1). Generated by "
               "`automation/cert/gen_gQJ1.py`.")
        stmt = ("    ∀ x ∈ Icc (4⁻¹ : ℝ) 2⁻¹, ∀ y ∈ Icc (2⁻¹ : ℝ) (5 / 8), 1 / 10 ^ 5 <\n"
                f"      (y - x) ^ (({lb} : ℝ)⁻¹ - 1) + ({lc} : ℝ) ^ ({lb} : ℝ)⁻¹ *\n"
                f"        (2 * gJw w₀ ((x + y) / 2) - Q {lb} x) ^ (({lb} : ℝ)⁻¹ - 1) *\n"
                f"          (DJr ((x + y) / 2) - Q1f {lb} x)")
        emit_assembly(mod, boxmods, f"[DIR] (6.26): assembly, {tag}", doc, f"gQJ1Tree_{tag}",
                      tree, ROOT, [f"gQJ1_{tag}_{k}s" for k in range(len(chunks))],
                      f"gQJ1_pos_{tag}",
                      f"**(6.26)** for {desc}: $-\\beta\\partial_xg_{{QJ,\\beta,c}}>10^{{-5}}$ on\n"
                      "$[\\frac14,\\frac12]\\times[\\frac12,\\frac58]$.", stmt,
                      f"gQJ1_of_tree {lb} {lc} " + ("(by norm_num [β₀]) (by norm_num)" if tag == "b0"
                                                    else "(by norm_num) (by norm_num [c₀])"),
                      header, FOOTER, write, DIR)
    print("modules:", allmods)


if __name__ == "__main__":
    main()
