def build_tree(bs, xl, xu, yl, yu):
    """The dyadic tree (nested tuples, None = leaf) of the partition `bs` of the rectangle;
    children in the order 00, 01, 10, 11 (first index: x upper half, second: y upper half)."""
    S = set(bs)
    used = []

    def rec(a, b, c, d, depth):
        if (a, b, c, d) in S:
            used.append((a, b, c, d))
            return None
        if depth > 40:
            raise ValueError("partition is not dyadic")
        mx, my = (a + b) / 2, (c + d) / 2
        return (rec(a, mx, c, my, depth + 1), rec(a, mx, my, d, depth + 1),
                rec(mx, b, c, my, depth + 1), rec(mx, b, my, d, depth + 1))

    t = rec(F(xl), F(xu), F(yl), F(yu), 0)
    assert sorted(used) == sorted(bs), "tree does not reproduce the partition"
    return t, used  # `used` is the order of DTree.boxes


def lean_tree(t):
    """Lean term of a DTree."""
    out = []

    def rec(t):
        if t is None:
            out.append(".leaf")
        else:
            out.append("(.node ")
            for i, c in enumerate(t):
                if i:
                    out.append(" ")
                rec(c)
            out.append(")")
    rec(t)
    s = "".join(out)
    # wrap long lines
    lines, cur = [], ""
    for tok in s.split(" "):
        if len(cur) + len(tok) + 1 > 96:
            lines.append(cur)
            cur = "    " + tok
        else:
            cur = (cur + " " + tok) if cur else tok
    lines.append(cur)
    return "\n".join(lines)


def q(x):
    """Lean rational literal of a Fraction."""
    x = F(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℚ)" if x.numerator >= 0 else f"(({x.numerator}) : ℚ)"
    if x.numerator < 0:
        return f"((-{-x.numerator}) / {x.denominator} : ℚ)"
    return f"({x.numerator} / {x.denominator} : ℚ)"


def dec(v, digits, up):
    """Decimal string of v rounded up/down at `digits` decimals."""
    s = mp.mpf(10) ** digits
    n = int(mp.ceil(v * s) if up else mp.floor(v * s))
    sign = "-" if n < 0 else ""
    n = abs(n)
    ip, fp = divmod(n, 10 ** digits)
    return f"{sign}{ip}.{fp:0{digits}d}"


def dq(sd):
    """Lean rational literal for a decimal string (parenthesized if negative)."""
    return f"({sd} : ℚ)" if not sd.startswith("-") else f"(({sd}) : ℚ)"


def J_val(x):
    return Jw(W0, mp.mpf(x.numerator) / x.denominator)


def DJ_val(x):
    xm = mp.mpf(x.numerator) / x.denominator
    return mp.sqrt(2) * mp.sqrt(2) * mp.erfinv(2 * (1 - xm) / W0 - 1)


