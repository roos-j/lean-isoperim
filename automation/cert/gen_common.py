def J_entry(name, x, margin=mp.mpf("1e-10"), digits=12):
    """Lean source of a certified table entry `name : JVal` for J(x), x in [1/2, 1]."""
    if x == 1:
        return f"/-- $J(1)=0$. -/\nabbrev {name} : JVal := JVal.one\n\n"
    xs = mp.mpf(x.numerator) / x.denominator
    v = J_val(x)
    sl, su = J_witness(xs, WL, WU)
    lo, hi = dec(v - margin, digits, False), dec(v + margin, digits, True)
    return (f"/-- Certified enclosure of $J({x})$. -/\n"
            f"theorem {name}_h : checkMem P11 [] (.J {q(x)} {sl} {su}) {dq(lo)} {dq(hi)} = true"
            f" := by\n  decide +kernel\n\n"
            f"/-- Certified value $J({x})$. -/\n"
            f"def {name} : JVal := JVal.mk' {q(x)} {dq(lo)} {dq(hi)} {sl} {su} {name}_h\n\n")


