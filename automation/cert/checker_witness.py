import mpmath as mp

mp.mp.dps = 50
SQ2 = mp.sqrt(2)


def Phi(z):
    return mp.ncdf(z)


def Phiinv(p):
    return SQ2 * mp.erfinv(2 * p - 1)


def gProf(t):
    return mp.npdf(Phiinv(t))


def Jw(w, x):
    return SQ2 * w * gProf((1 - x) / w)


def w0():
    return mp.findroot(lambda w: Jw(w, mp.mpf(1) / 2) - mp.mpf(1) / 2, mp.mpf("0.8957"))


def erfcinv(y):
    return mp.erfinv(1 - y)


def dec(v, digits, up):
    """Decimal string of v rounded up/down at `digits` decimals."""
    s = mp.mpf(10) ** digits
    n = mp.ceil(v * s) if up else mp.floor(v * s)
    n = int(n)
    sign = "-" if n < 0 else ""
    n = abs(n)
    ip, fp = divmod(n, 10 ** digits)
    return f"{sign}{ip}.{fp:0{digits}d}"


def J_witness(x, wl, wu, margin=mp.mpf("1e-13"), digits=16):
    x, wl, wu = mp.mpf(x), mp.mpf(wl), mp.mpf(wu)
    tlo, thi = (1 - x) / wu, (1 - x) / wl
    sl = erfcinv(2 * min(tlo, 1 - thi)) + margin
    su = max(erfcinv(2 * min(thi, 1 - tlo)) - margin, 0)
    return dec(sl, digits, True), dec(su, digits, False)


def DJ_witness(x, wl, wu, margin=mp.mpf("1e-13"), digits=16):
    x, wl, wu = mp.mpf(x), mp.mpf(wl), mp.mpf(wu)
    tlo, thi = (1 - x) / wu, (1 - x) / wl
    zl = mp.erfinv(2 * tlo - 1) - margin
    zu = mp.erfinv(2 * thi - 1) + margin
    return dec(zl, digits, False), dec(zu, digits, True)


