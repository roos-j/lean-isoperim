"""Generator of the certificate files for (6.27) ([DIR] §6.6.2, Proposition 6.12):
g_{QJ,2}(x,y) > 1e-7 on [1/4, 1/2] x [5/8, 1], with the admissible partition `g_QJ_2` of the
paper's `partitions.py` (5779 rectangles; refined only where the case of the enclosure of J
cannot be decided by the rational enclosure of x0 or the lower bound is too small).

This file was automatically generated by Claude.

Usage (from the repository root): python3 automation/cert/gen_gQJ2.py
Writes Isoperim/DIR/6_Proof_Two_Point_Inequality/6_6_Case_QJ_aux_cert_g2_*.lean.
"""
import mpmath as mp
from fractions import Fraction as F
from gen_common import boxes, build_tree, header, FOOTER, write, DIR
from gen_qj_common import (J, Q, X0, refine, emit_boxes, emit_assembly, wrap_doc, Jw_entry,
                           J_entry, mpf)
from gen_gQJ1 import case

NTAB = 300
NBOX = 700
THR = mp.mpf("1e-7") + mp.mpf("1e-9")
ROOT = (F(1, 4), F(1, 2), F(5, 8), F(1))


def lo(xl, xu, yl, yu):
    """`Auto.DIR.g_QJ_2_lo` (floating point); -inf if the case is undecided."""
    k = case(xl, xu, yl, yu)
    if k is None:
        return -mp.inf
    ml, mu = (xl + yl) / 2, (xu + yu) / 2
    Jbar = [J(mu), J(ml), J(X0)][k]
    return mp.sqrt(mpf(yl - xu) ** 2 + J(yu) ** 2) + Q(mp.sqrt(2), xl) - 2 * Jbar


def main():
    bs = [r for b in boxes("g_QJ_2") for r in refine(lo, b, THR)]
    tree, order = build_tree(bs, *ROOT)
    print("g_QJ_2", len(boxes("g_QJ_2")), "->", len(order))
    ys = sorted({b[3] for b in order})
    ms = sorted({m for (xl, xu, yl, yu) in order for m in ((xl + yl) / 2, (xu + yu) / 2)})
    nJ = {p: f"tQJ2J_{i}" for i, p in enumerate(ys)}
    nW = {p: f"tQJ2W_{i}" for i, p in enumerate(ms)}
    entries = [J_entry(nJ[p], p) for p in ys] + [Jw_entry(nW[p], p) for p in ms]
    tabmods = []
    for k in range(0, len(entries), NTAB):
        mod = f"6_6_Case_QJ_aux_cert_g2_tab_{k // NTAB}"
        tabmods.append(mod)
        doc = ("Certified values of $J$ and $J_{w_0}$ (table entries) for the box certificates of "
               f"(6.27) ([DIR], §6.6.2), part {k // NTAB}. Generated by "
               "`automation/cert/gen_gQJ2.py`.")
        txt = header(["6_6_Case_QJ_aux_cert"],
                     f"[DIR] (6.27): table of $J$, $J_{{w_0}}$, part {k // NTAB}", wrap_doc(doc))
        txt += "".join(entries[k:k + NTAB]) + FOOTER
        write(f"{DIR}/{mod}.lean", txt)
    chunks = [order[i:i + NBOX] for i in range(0, len(order), NBOX)]
    boxmods = []
    for k, chunk in enumerate(chunks):
        mod = f"6_6_Case_QJ_aux_cert_g2_{k}"
        boxmods.append(mod)
        doc = (f"Box certificates of (6.27) ([DIR], §6.6.2), part {k}: "
               "$\\underline{g_{QJ,2}}>10^{-7}$ on each rectangle of the partition (one kernel "
               "evaluation each). Generated by `automation/cert/gen_gQJ2.py`.")

        def proof(p):
            xl, xu, yl, yu = p
            ml, mu = (xl + yl) / 2, (xu + yu) / 2
            return f"gQJ2_box {case(*p)} _ {nJ[yu]} {nW[ml]} {nW[mu]} (by decide +kernel)"
        emit_boxes(f"gQJ2_{k}", mod, tabmods, f"[DIR] (6.27): box certificates, part {k}", doc,
                   chunk, proof, "gQJ2_fl", header, FOOTER, write, DIR)
    mod = "6_6_Case_QJ_aux_cert_g2"
    doc = ("Assembly of the computer-assisted proof of (6.27) ([DIR], §6.6.2, Proposition 6.12): "
           "the dyadic tree of the partition (`g_QJ_2` of the paper's `partitions.py`), the box "
           "certificates and soundness of partitioning (`Auto.DIR.gQJ2_of_tree`, via [DIR] "
           "Fact 4.1). Generated by `automation/cert/gen_gQJ2.py`.")
    stmt = ("    ∀ x ∈ Icc (4⁻¹ : ℝ) 2⁻¹, ∀ y ∈ Icc (5 / 8 : ℝ) 1, 1 / 10 ^ 7 <\n"
            "      ((y - x) ^ 2 + J y ^ 2) ^ (2⁻¹ : ℝ) + Q 2⁻¹ x - 2 * gJw w₀ ((x + y) / 2)")
    emit_assembly(mod, boxmods, "[DIR] (6.27): assembly", doc, "gQJ2Tree", tree, ROOT,
                  [f"gQJ2_{k}s" for k in range(len(chunks))], "gQJ2_pos",
                  "**(6.27)**: $g_{QJ,2}>10^{-7}$ on $[\\frac14,\\frac12]\\times[\\frac58,1]$.",
                  stmt, "gQJ2_of_tree", header, FOOTER, write, DIR)
    print("modules:", tabmods + boxmods + [mod])


if __name__ == "__main__":
    main()
