WL, WU = mpf('0.895769326048'), mpf('0.895769326057')
q = lambda s: mpf(F(s).numerator) / F(s).denominator
L = lambda x: f"({F(x).numerator}/{F(x).denominator} : ℚ)" if F(x).denominator != 1 else f"({F(x).numerator} : ℚ)"
def jw(x):
    x = F(x)
    if x == 1: return "(0, 0)"
    a, b = cw.J_witness(mpf(x.numerator) / x.denominator, WL, WU); return f"({a}, {b})"
def dw(x):
    x = F(x); a, b = cw.DJ_witness(mpf(x.numerator) / x.denominator, WL, WU); return f"({a}, {b})"
def pick(rects, f, n=20):
    random.seed(0); E[0] = mpf(0)
    vs = sorted((f(r), i) for i, r in enumerate(rects))
    worst = [i for _, i in vs[:n]]; rest = [i for _, i in vs[n:]]
    return worst + random.sample(rest, n)
