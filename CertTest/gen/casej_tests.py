WLs, WUs = '0.895769326048', '0.895769326057'
WL, WU = mpf(WLs), mpf(WUs)
WLq, WUq = F(WLs), F(WUs)
SQPI_LO, SQPI_HI = F('1.772453850905516027'), F('1.772453850905516028')
PREC, ME = 64, 20
B0 = F(50057, 100000)
BSTR = "(50057 / 100000)"


def q(s):
    return mpf(F(s).numerator) / F(s).denominator


def L(x):
    x = F(x)
    return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"


def rdn(v):
    return F(math.floor(v * 2 ** PREC), 2 ** PREC)


def rup(v):
    return F(math.ceil(v * 2 ** PREC), 2 ** PREC)


def eNq(N, v):
    s, t = F(0), F(1)
    for k in range(N):
        s += t / math.factorial(k)
        t *= -v
    return s


def lit(x):
    """A rational literal for a bound of a table entry."""
    x = F(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℚ)"
    return f"({x.numerator} / {x.denominator} : ℚ)"


def nm(x):
    x = F(x)
    return f"{x.numerator}_{x.denominator}"


table = {}   # name -> Lean definition body


def tJ(x):
    x = F(x)
    name = "j_" + nm(x)
    if name not in table:
        if x == 1:
            table[name] = "Cert.ofJOne"
        else:
            sl, su = cw.J_witness(mpf(x.numerator) / x.denominator, WL, WU)
            a = rdn(WLq * eNq(2 * ME + 2, F(sl) ** 2) / SQPI_HI)
            b = rup(WUq * eNq(2 * ME + 1, F(su) ** 2) / SQPI_LO)
            table[name] = (f"Cert.ofJ Test.P Test.hw {L(x)}\n    {lit(a)}\n    {lit(b)}\n"
                           f"    {sl} {su} (by decide +kernel)")
    return "T." + name


def tDJ(x):
    x = F(x)
    assert x < 1
    name = "dj_" + nm(x)
    if name not in table:
        zl, zu = cw.DJ_witness(mpf(x.numerator) / x.denominator, WL, WU)
        table[name] = (f"Cert.ofDJ Test.P Test.hw {L(x)}\n    {lit(2 * F(zl))} {lit(2 * F(zu))}"
                       f"\n    ({zl}) ({zu}) (by decide +kernel)")
    return "T." + name


def tJx0():
    if "jx0" not in table:
        a, b = rdn(WLq / SQPI_HI), rup(WUq / SQPI_LO)
        table["jx0"] = f"Cert.ofJx0 Test.P Test.hw\n    {lit(a)} {lit(b)}\n    (by decide +kernel)"
    return "T.jx0"


def tPow(h, k):
    """h^(k - 1/b) (k = 1..6; k = 0 means 1/b) for b = B0."""
    h = F(h)
    rs = f"(1 / {BSTR})" if k == 0 else f"({k} - 1 / {BSTR})"
    r = 1 / B0 if k == 0 else k - 1 / B0
    name = f"pw_{nm(h)}_{k}"
    if name not in table:
        if h == 0:
            table[name] = f"Cert.ofRpowZero {rs} (by norm_num)"
        else:
            mp.dps = 60
            v = (mpf(h.numerator) / h.denominator) ** (mpf(r.numerator) / r.denominator)
            lo = F(str(mp.nstr(v * (1 - mpf('1e-15')), 50, min_fixed=-mp.inf, max_fixed=mp.inf)))
            hi = F(str(mp.nstr(v * (1 + mpf('1e-15')), 50, min_fixed=-mp.inf, max_fixed=mp.inf)))
            mp.dps = 50
            table[name] = (f"Cert.ofRpow Test.P Test.hw {L(h)} {rs}\n    {lit(rdn(lo))}\n"
                           f"    {lit(rup(hi))}\n    (by decide +kernel)")
    return "T." + name


def pick(rects, f, n=20):
    random.seed(0); E[0] = mpf(0)
    vs = sorted((f(r), i) for i, r in enumerate(rects))
    worst = [i for _, i in vs[:n]]; rest = [i for _, i in vs[n:]]
    return worst + random.sample(rest, n)


