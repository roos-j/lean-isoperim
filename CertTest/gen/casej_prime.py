def sel(rects, f, specs):
    """specs: list of (label, predicate on index or 'worst'/'random', count)."""
    random.seed(1); E[0] = mpf(0)
    vals_ = [f(r) for r in rects]
    order = sorted(range(len(rects)), key=lambda i: vals_[i])
    chosen, labels = [], {}
    for lab, pred, n in specs:
        if pred == 'worst': cand = order
        elif pred == 'random': cand = random.sample(range(len(rects)), len(rects))
        else: cand = [i for i in order if pred(rects[i])]
        k = 0
        for i in cand:
            if k >= n: break
            if i not in labels: chosen.append(i); labels[i] = lab; k += 1
    return chosen, labels, vals_

